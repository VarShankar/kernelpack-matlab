function ibamr_surface_trajectory_checks()
%IBAMR_SURFACE_TRAJECTORY_CHECKS Validate the committed 3D FSI trajectory.

root = fileparts(fileparts(mfilename('fullpath')));
folder = fullfile(root, 'data', 'ibamr_rbc_3d', 'trajectory');
trajectory = kp.manifold.IBAMRSurfaceTrajectory(folder, 'Xi', 6, 'Degree', 7);

assert(numel(trajectory.Times) == 401, ...
    'The production trajectory must contain 401 frames.');
assert(size(trajectory.MaterialSites, 1) == 2562, ...
    'The production membrane must contain 2562 material markers.');
assert(size(trajectory.Faces, 1) == 5120, ...
    'The production membrane must contain 5120 triangular faces.');
assert(abs(trajectory.Times(end) - 2) < 1.0e-12, ...
    'The production trajectory must reach t=2.');

material = trajectory.initialMaterial();
initialGeometry = trajectory.geometry(material, 0);
finalGeometry = trajectory.geometry(material, trajectory.Times(end));
assert(all(isfinite(finalGeometry.X), 'all'), ...
    'The reconstructed final geometry contains non-finite coordinates.');
assert(all(finalGeometry.weights > 0), ...
    'The SBF surface quadrature must have positive weights.');
assert(max(abs(vecnorm(finalGeometry.normals, 2, 2) - 1)) < 1.0e-12, ...
    'The SBF normals must be unit length.');

initialPositionError = norm(initialGeometry.X - trajectory.Positions(:, :, 1), 'fro') / ...
    norm(trajectory.Positions(:, :, 1), 'fro');
finalPositionError = norm(finalGeometry.X - trajectory.Positions(:, :, end), 'fro') / ...
    norm(trajectory.Positions(:, :, end), 'fro');
assert(max(initialPositionError, finalPositionError) < 1.0e-4, ...
    'The reduced SBF model does not resolve the native membrane markers.');
initialAreaError = abs(initialGeometry.area - trajectory.Diagnostics.area(1)) / ...
    trajectory.Diagnostics.area(1);
finalAreaError = abs(finalGeometry.area - trajectory.Diagnostics.area(end)) / ...
    trajectory.Diagnostics.area(end);
assert(max(initialAreaError, finalAreaError) < 1.0e-2, ...
    'The SBF quadrature area disagrees with the triangulated membrane area.');

velocityCheck = trajectory.validateVelocityInterpolation();
assert(velocityCheck.relativeRMS < 1.0e-3, ...
    'The exported IB velocities disagree with the trajectory derivative.');
testField = 1 + material.U(:, 1) - 0.3 * material.U(:, 2) .* material.U(:, 3);
interpolatedField = trajectory.interpolateMaterialField( ...
    material, testField, material);
fieldInterpolationError = norm(interpolatedField - testField) / norm(testField);
assert(fieldInterpolationError < 1.0e-9, ...
    'The local tangent-plane interpolant does not reproduce its source data.');
assert(abs(trajectory.Diagnostics.relative_area_change(end)) < 1.0e-5, ...
    'The FSI membrane area drift is too large.');
assert(abs(trajectory.Diagnostics.relative_volume_change(end)) < 5.0e-4, ...
    'The FSI membrane volume drift is too large.');

disp('IBAMR surface trajectory checks passed');
fprintf('  controls: %d / %d\n', numel(trajectory.ControlIds), ...
    size(trajectory.MaterialSites, 1));
fprintf('  SBF position errors: [%.3e, %.3e]\n', ...
    initialPositionError, finalPositionError);
fprintf('  SBF area errors: [%.3e, %.3e]\n', ...
    initialAreaError, finalAreaError);
fprintf('  velocity interpolation relative RMS: %.3e\n', ...
    velocityCheck.relativeRMS);
fprintf('  material-field interpolation residual: %.3e\n', ...
    fieldInterpolationError);
end
