function manifold_convergence_results_checks()
%MANIFOLD_CONVERGENCE_RESULTS_CHECKS Verify tabular convergence exports.

N = [100, 400, 1600];
h = N.^(-1 / 2);
template = struct( ...
    'xi', 2, ...
    'exactStartup', true, ...
    'N', N, ...
    'h', h, ...
    'dt', 0.1 * h.^(2 / 3), ...
    'nsteps', [10, 20, 40], ...
    'relerr', h.^2, ...
    'rate', [NaN, 2, 2], ...
    'normalRMSAngle', [0, 0, 0], ...
    'rearrangementTimes', {{[], [], []}}, ...
    'updateStats', {{struct(), struct(), struct()}}, ...
    'solveStats', {{struct(), struct(), struct()}});
results = [template, template];
results(2).xi = 4;
results(2).relerr = h.^4;
results(2).rate = [NaN, 4, 4];

T = kp.manifold.convergenceResultsTable(results);

assert(height(T) == 6, 'The export must contain one row per (xi, N) pair.');
assert(all(T.exactStartup), 'Exact-startup metadata was not preserved.');
assert(max(abs(T.fitRate(T.xi == 2) - 2)) < 100 * eps, ...
    'The xi=2 fitted rate is incorrect.');
assert(max(abs(T.fitRate(T.xi == 4) - 4)) < 100 * eps, ...
    'The xi=4 fitted rate is incorrect.');
assert(all(abs(T.localRate([2, 3, 5, 6]) - [2; 2; 4; 4]) < 100 * eps), ...
    'Local rates were not flattened correctly.');
assert(ismember('normalRMSAngle', T.Properties.VariableNames), ...
    'Numeric diagnostics must be retained in the CSV table.');
assert(~ismember('updateStats', T.Properties.VariableNames), ...
    'Structure-valued diagnostics must remain in the MAT file.');

disp('manifold convergence results checks passed');
end
