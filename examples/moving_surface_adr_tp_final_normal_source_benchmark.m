function bench = moving_surface_adr_tp_final_normal_source_benchmark(varargin)
%MOVING_SURFACE_ADR_TP_FINAL_NORMAL_SOURCE_BENCHMARK Normal-source comparison.
%   Compares exact, PCA, and SBF normals for the
%   accelerated moving-surface ADR discretization.  Timings include normal estimation,
%   SBF subset selection/factorization/evaluation, operator assembly, and
%   time stepping.

parser = inputParser();
parser.addParameter('Cases', ["anisotropic_ellipsoid", "breathing_torus"]);
parser.addParameter('XiVals', [2, 4, 6], @(x) isnumeric(x) && isvector(x));
parser.addParameter('NVals', [576, 1024, 1600], @(x) isnumeric(x) && isvector(x));
parser.addParameter('TorusNVals', [1600, 2304, 3136], @(x) isnumeric(x) && isvector(x));
parser.addParameter('DtScale', 0.05, @(x) isnumeric(x) && isscalar(x));
parser.addParameter('OutputPrefix', fullfile(pwd, ...
    'moving_surface_adr_tp_final_normal_source_benchmark'));
parser.addParameter('GlobalSBFMinControlPointCount', 48, @(x) isnumeric(x) && isscalar(x));
parser.addParameter('UseRearrangement', true, @(x) islogical(x) && isscalar(x));
parser.addParameter('QualityThreshold', 1.75, @(x) isnumeric(x) && isscalar(x));
parser.addParameter('PredictiveLookaheadSteps', 3, @(x) isnumeric(x) && isscalar(x));
parser.addParameter('MinStepsBetweenRearrangements', 8, @(x) isnumeric(x) && isscalar(x));
parser.addParameter('RearrangementTransferMode', "localTp", @(x) isstring(x) || ischar(x));
parser.addParameter('MassCorrectionMode', "balance", @(x) isstring(x) || ischar(x));
parser.addParameter('ExactStartup', true, @(x) islogical(x) && isscalar(x));
parser.addParameter('GlobalGMRESTolerance', 1.0e-12, ...
    @(x) isnumeric(x) && isscalar(x) && x > 0);
parser.addParameter('SaveAfterEach', true, @(x) islogical(x) && isscalar(x));
parser.addParameter('ContinueOnError', true, @(x) islogical(x) && isscalar(x));
parser.addParameter('WarmParallelPool', true, @(x) islogical(x) && isscalar(x));
parser.parse(varargin{:});
opts = parser.Results;

if opts.WarmParallelPool
    warmParallelPool();
end

cases = string(opts.Cases);
xiVals = opts.XiVals(:).';
normalModes = ["exact", "pca", "calibratedSbf"];
rows = repmat(emptyRow(), 0, 1);
rowIndex = 0;
partialPath = string(opts.OutputPrefix) + ".mat";

for caseName = cases
    problem = moving_surface_adr_tp_problem(caseName);
    if caseName == "breathing_torus"
        nvals = opts.TorusNVals(:).';
    else
        nvals = opts.NVals(:).';
    end

    for xi = xiVals
        for N = nvals
            for mode = normalModes
                fprintf('\nFinal normal benchmark case=%s xi=%d N=%d normal=%s\n', ...
                    caseName, xi, N, mode);
                row = makeBaseRow(caseName, problem.title, problem.finalTime, xi, N, mode);
                try
                    tic;
                    result = kp.manifold.runLagrangianMovingADRConvergence( ...
                        problem, xi, N, opts.DtScale, ...
                        'FinalTime', problem.finalTime, ...
                        'DiffMatUpdateMethod', 'defect', ...
                        'DefectTolerance', 1.0e-6, ...
                        'MaxDefectIterations', 4, ...
                        'SpectrumCheck', false, ...
                        'HyperviscosityUpdateMode', 'adaptiveGeometry', ...
                        'NormalMode', mode, ...
                        'NormalNeighborCount', 32, ...
                        'GlobalSBFNormalDegree', 7, ...
                        'GlobalSBFNormalOrder', 8, ...
                        'GlobalSBFBalanceSafety', 0.1, ...
                        'GlobalSBFControlPointScale', 1 / 3, ...
                        'GlobalSBFMinControlPointCount', opts.GlobalSBFMinControlPointCount, ...
                        'UseRearrangement', opts.UseRearrangement, ...
                        'QualityThreshold', opts.QualityThreshold, ...
                        'PredictiveLookaheadSteps', opts.PredictiveLookaheadSteps, ...
                        'MinStepsBetweenRearrangements', opts.MinStepsBetweenRearrangements, ...
                        'RearrangementTransferMode', opts.RearrangementTransferMode, ...
                        'MassCorrectionMode', opts.MassCorrectionMode, ...
                        'ExactStartup', opts.ExactStartup, ...
                        'GlobalGMRESTolerance', opts.GlobalGMRESTolerance, ...
                        'RecordMassDiagnostics', true);
                    row.elapsedSeconds = toc;
                    row.status = "ok";
                    row.dt = result.dt;
                    row.nsteps = result.nsteps;
                    row.relerr = result.relerr;
                    row.massRelError = result.massRelError;
                    row.balanceRelResidual = result.balanceRelResidual;
                    row.normalRMSAngle = result.normalRMSAngle;
                    row.normalMaxAngle = result.normalMaxAngle;
                    row.normalControlPointCount = result.normalControlPointCount;
                    row.normalControlPointFraction = result.normalControlPointFraction;
                    row.normalControlFillDistance = result.normalControlFillDistance;
                    row.numRearrangements = result.numRearrangements;
                    row.initialQuality = result.initialQuality;
                    row.finalQuality = result.finalQuality;
                    row.maxQuality = result.maxQuality;
                    row.updateDirect = result.updateStats{1}.direct;
                    row.updateDefectCorrected = result.updateStats{1}.defectCorrected;
                    row.updateFallback = result.updateStats{1}.defectFailedRefactored;
                    row.iluRefreshes = result.solveStats{1}.iluRefreshes;
                    row.gmresSolves = result.solveStats{1}.gmresSolves;
                    row.gmresIterations = result.solveStats{1}.gmresIterations;
                    row.hyperviscosityMinPower = result.updateStats{1}.minHyperviscosityPower;
                    row.hyperviscosityMaxPower = result.updateStats{1}.maxHyperviscosityPower;
                    fprintf('  relerr=%.6e normalRMS=%.3e wall=%.2fs\n', ...
                        row.relerr, row.normalRMSAngle, row.elapsedSeconds);
                catch ME
                    row.elapsedSeconds = toc;
                    row.status = "failed";
                    row.message = string(ME.message);
                    fprintf('  FAILED: %s\n', ME.message);
                    if ~opts.ContinueOnError
                        rethrow(ME);
                    end
                end
                rowIndex = rowIndex + 1;
                rows(rowIndex, 1) = row;
                if opts.SaveAfterEach
                    bench = makeBench(rows);
                    save(partialPath, 'bench');
                    writetable(bench.table, string(opts.OutputPrefix) + ".csv");
                end
            end
        end
    end
end

bench = makeBench(rows);
save(partialPath, 'bench');
writetable(bench.table, string(opts.OutputPrefix) + ".csv");
end

function warmParallelPool()
try
    pool = gcp('nocreate');
    if isempty(pool)
        parpool('Processes');
    end
catch ME
    warning('kp:examples:ParallelPoolWarmupFailed', ...
        'Unable to warm the parallel pool before timing: %s', ME.message);
end
end

function bench = makeBench(rows)
bench = struct();
bench.rows = rows;
bench.table = struct2table(rows);
end

function row = makeBaseRow(caseName, titleText, finalTime, xi, N, normalMode)
row = emptyRow();
row.caseName = string(caseName);
row.title = string(titleText);
row.finalTime = finalTime;
row.xi = xi;
row.N = N;
row.sqrtN = sqrt(N);
row.normalMode = string(normalMode);
end

function row = emptyRow()
row = struct( ...
    'caseName', "", ...
    'title', "", ...
    'finalTime', NaN, ...
    'dt', NaN, ...
    'nsteps', NaN, ...
    'xi', 0, ...
    'N', 0, ...
    'sqrtN', NaN, ...
    'normalMode', "", ...
    'status', "pending", ...
    'message', "", ...
    'elapsedSeconds', NaN, ...
    'relerr', NaN, ...
    'massRelError', NaN, ...
    'balanceRelResidual', NaN, ...
    'normalRMSAngle', NaN, ...
    'normalMaxAngle', NaN, ...
    'normalControlPointCount', NaN, ...
    'normalControlPointFraction', NaN, ...
    'normalControlFillDistance', NaN, ...
    'numRearrangements', NaN, ...
    'initialQuality', NaN, ...
    'finalQuality', NaN, ...
    'maxQuality', NaN, ...
    'updateDirect', NaN, ...
    'updateDefectCorrected', NaN, ...
    'updateFallback', NaN, ...
    'iluRefreshes', NaN, ...
    'gmresSolves', NaN, ...
    'gmresIterations', NaN, ...
    'hyperviscosityMinPower', NaN, ...
    'hyperviscosityMaxPower', NaN);
end
